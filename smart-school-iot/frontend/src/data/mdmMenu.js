/**
 * Returns today's day of week name (defaults to Monday if Sunday)
 */
export function getTodayDayName() {
  const dayNames = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];
  const today = dayNames[new Date().getDay()];
  return today === 'Sunday' ? 'Monday' : today;
}

/**
 * Returns the menu for a given zone and day of week
 */
export function getZoneMenu(zoneId = 2, dayName = null) {
  const zone = AP_MDM_ZONES[zoneId] || AP_MDM_ZONES[2];
  const day = dayName || getTodayDayName();
  return zone.schedule[day] || zone.schedule['Monday'];
}
